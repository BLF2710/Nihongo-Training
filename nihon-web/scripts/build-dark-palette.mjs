#!/usr/bin/env node
// Writes src/dark-palette.css: the dark theme, made by mirroring Tailwind's own colour scales.
//   node scripts/build-dark-palette.mjs
//
// Every Tailwind colour class reads a CSS variable (bg-gray-50 -> var(--color-gray-50)). Under `.dark` this file
// gives each shade the value of its mirror (50 <-> 950, 100 <-> 900, ... 500 stays), so pale backgrounds become
// dark, dark text becomes light, and accents keep their hue, without a `dark:` class on every element.
// Re-run it after upgrading Tailwind or when the site starts using a new colour family.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const theme = readFileSync(join(root, "node_modules/tailwindcss/theme.css"), "utf8");
const FAMILIES = ["gray", "emerald", "teal", "green", "indigo", "blue", "purple", "red", "orange", "amber"];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const value = (family, shade) => {
  const match = theme.match(new RegExp(`--color-${family}-${shade}:\\s*([^;]+);`));
  if (!match) throw new Error(`Tailwind has no --color-${family}-${shade}`);
  return match[1].trim();
};

// Greys carry surfaces, borders and text, so they are tuned rather than mirrored exactly:
// page < chips < cards, borders that stay visible on cards, and secondary text that stays readable.
const GRAY = {
  50: value("gray", 950), 100: "oklch(20% 0.032 263)", 200: "oklch(33% 0.03 258)", 300: value("gray", 700),
  400: "oklch(66% 0.024 262)", 500: value("gray", 400), 600: "oklch(80% 0.02 260)", 700: value("gray", 300),
  800: value("gray", 200), 900: value("gray", 100), 950: value("gray", 50),
};
const mirror = shade => (shade === 500 ? 500 : 1000 - shade);
const lines = [];
for (const family of FAMILIES) {
  for (const shade of SHADES) lines.push(`  --color-${family}-${shade}: ${family === "gray" ? GRAY[shade] : value(family, mirror(shade))};`);
}

const css = `/* Generated by scripts/build-dark-palette.mjs. Do not edit by hand. */
/* The dark theme: Tailwind's colour scales mirrored, so every existing colour class adapts. */
.dark {
  color-scheme: dark;
  /* White surfaces (cards, inputs) become the darkest raised surface; white text on accents becomes dark. */
  --color-white: oklch(24% 0.03 262);
${lines.join("\n")}
}
`;
writeFileSync(join(root, "src/dark-palette.css"), css);
console.log(`Wrote src/dark-palette.css (${FAMILIES.length} colour families).`);
